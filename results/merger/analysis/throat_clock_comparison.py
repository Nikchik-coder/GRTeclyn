#!/usr/bin/env python3
"""Per-throat clock comparison: does the binary environment move a throat off
the isolated throat's own schedule?  (Forward Plan, Phase 0, item 1.)

Every arm writes binary_throat_diagnostics.dat: per throat, per step, the
minimum chi and minimum lapse in that throat's half-space.  For a drainhole
those minima sit at the COMPACTIFIED ORIGIN (the other universe's infinity,
chi ~ rbar^4), not at the throat, so what is compared here is each throat's
origin monitor against the isolated throat's -- the same quantity from the same
code on the same clock, normalised to its own t = 0.  It is gauge-dependent and
it is not the areal radius; the areal-radius version needs plotfiles that the
binary arms did not keep (the V1 scout will).  What it CAN say: whether a throat
in a binary leaves the isolated curve before the isolated throat itself turns
over (t = 26), i.e. whether the companion selects a branch early, or whether
the curves lie on top of each other until the plunge.

Reads only the packed tree.  Writes single_throat/CLOCK_COMPARISON.md and
figures/throat_clock_comparison.png.
"""
from __future__ import annotations

import pathlib
import sys

import numpy as np

REFERENCE = "single_hold_t100"
# fixed times at which each throat's origin chi is read, as log10(chi/chi0)
MARKS = [10.0, 20.0, 26.0, 30.0, 40.0, 50.0, 60.0]
T_VERDICT = 30.0    # pre-contact for every d = 12 arm (head-on contact ~ 30)
DEX_TOL = 0.10      # |delta log10| below this is "same"
FLOOR = 1.0e-8
T_TURNOVER = 26.0   # isolated throat's areal turnover (INSTABILITY.md)

# columns after time in binary_throat_diagnostics.dat
COL = dict(sep=0, xA=1, yA=2, zA=3, chiA=4, lapseA=5,
           xB=6, yB=7, zB=8, chiB=9, lapseB=10)

SKIP = ("bbh_control",)   # vacuum controls: no throat, no file


def read_stream(path: pathlib.Path):
    rows = [ln.split() for ln in path.read_text().splitlines()
            if ln.strip() and not ln.startswith("#")]
    if not rows:
        return np.empty(0), np.empty((0, 0))
    a = np.array([[float(x) for x in r] for r in rows])
    return a[:, 0], a[:, 1:]


def floor_time(t, chi):
    idx = np.where(chi <= 1.5 * FLOOR)[0]
    return float(t[idx[0]]) if idx.size else None


def at(t, y, tt):
    """Value of y at time tt (nearest sample), or None if the run ends first."""
    if tt > t[-1] + 0.3:
        return None
    return float(y[int(np.argmin(np.abs(t - tt)))])


def describe(t, chi, lapse):
    chi0 = chi[0]
    lr = np.log10(chi / chi0)
    out = {"t_end": float(t[-1]), "chi0": chi0, "t0": float(t[0])}
    k = int(np.argmax(lr))
    out["t_max"] = float(t[k])
    out["lr_max"] = float(lr[k])
    out["floor"] = floor_time(t, chi)
    for tt in MARKS:
        out[tt] = at(t, lr, tt)
    return out


def fmt(v):
    return "-" if v is None else f"{v:.1f}"


def main() -> int:
    root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".")
    camp = root / "campaign"
    ref_path = camp / REFERENCE / "binary_throat_diagnostics.dat"
    if not ref_path.exists():
        print("reference stream missing:", ref_path)
        return 1
    t_ref, c_ref = read_stream(ref_path)
    ref = describe(t_ref, c_ref[:, COL["chiA"]], c_ref[:, COL["lapseA"]])

    arms = []
    for d in sorted(camp.iterdir()):
        if d.name == REFERENCE or any(s in d.name for s in SKIP):
            continue
        p = d / "binary_throat_diagnostics.dat"
        if not p.exists():
            continue
        t, c = read_stream(p)
        if t.size < 10:
            continue
        rowA = describe(t, c[:, COL["chiA"]], c[:, COL["lapseA"]])
        has_B = np.all(np.isfinite(c[:, COL["chiB"]])) and c[0, COL["chiB"]] < 1.0
        rowB = describe(t, c[:, COL["chiB"]], c[:, COL["lapseB"]]) if has_B else None
        arms.append((d.name, t, c, rowA, rowB))

    lines = []
    L = lines.append
    L("# Per-throat clock comparison against the isolated throat")
    L("")
    L("Generated by `analysis/throat_clock_comparison.py` from the packed streams. Do not")
    L("hand-edit; re-run the packer instead.")
    L("")
    L("**What is compared.** Each throat's origin monitor -- the minimum chi in its")
    L("half-space, which for a drainhole sits at the compactified origin (chi ~ rbar^4),")
    L("not at the throat -- normalised to its own t = 0, against the same quantity for")
    L(f"`{REFERENCE}`. Gauge-dependent, and not the areal radius: a clock comparison,")
    L("not a radius comparison. The times below are when the monitor first reaches the")
    L("given multiple of its t = 0 value, and when it hits the 1e-8 floor.")
    L("")
    L("## The isolated throat's own schedule")
    L("")
    L("| quantity | value |")
    L("|---|---|")
    L(f"| chi at the origin, t = 0 | {ref['chi0']:.3e} |")
    L(f"| peak of chi/chi0 | x{10**ref['lr_max']:.1f} at t = {ref['t_max']:.1f} (settling, then the mode drives it back down) |")
    for tt in MARKS:
        L(f"| log10(chi/chi0) at t = {tt:.0f} | {fmt(ref[tt])} |")
    L(f"| floor (1e-8) | t = {fmt(ref['floor'])} |")
    L(f"| areal turnover (INSTABILITY.md) | t = {T_TURNOVER:.0f} |")
    L("")
    L("The origin chi first *rises* (the unresolved chi ~ rbar^4 cells settle within a")
    L("unit) and then *falls* as the throat contracts, reaching the floor at t = 61.3.")
    L("The fall is the clock. A throat that sits *below* the isolated curve at the same")
    L("t is further along the contraction (`early`); one that sits *above* it is being")
    L("held open (`late`).")
    L("")
    L("## Every arm, both throats")
    L("")
    L("log10(chi_origin / its t = 0 value) at fixed times; `-` = the run ended first.")
    L(f"Verdict at t = {T_VERDICT:.0f} (before any d = 12 pair has made contact): the")
    L(f"difference from the isolated throat in dex, `same` within {DEX_TOL:.2f}.")
    L("")
    L("| arm | throat | ran to | peak x / at t | " + " | ".join(f"t={tt:.0f}" for tt in MARKS) + " | floor | verdict |")
    L("|---|---|---|---|" + "---|" * len(MARKS) + "---|---|")

    def verdict(row):
        v = row.get(T_VERDICT)
        r = ref.get(T_VERDICT)
        if row["t0"] > 1.0:
            return "restart -- own clock only"
        if v is None or r is None:
            return "too short"
        d = v - r
        if d < -DEX_TOL:
            return f"early ({d:+.2f} dex)"
        if d > DEX_TOL:
            return f"late ({d:+.2f} dex)"
        return f"same ({d:+.2f} dex)"

    def rowfmt(name, lab, row, tag):
        cells = " | ".join(fmt(row[tt]) if row[tt] is None else f"{row[tt]:+.2f}" for tt in MARKS)
        return (f"| {name} | {lab} | {row['t_end']:.1f} | x{10**row['lr_max']:.1f} / {row['t_max']:.1f} | "
                f"{cells} | {fmt(row['floor'])} | {tag} |")

    L(rowfmt(f"**{REFERENCE}**", "A", ref, "reference"))
    for name, t, c, rowA, rowB in arms:
        for lab, row in (("A", rowA), ("B", rowB)):
            if row is None:
                continue
            L(rowfmt(f"`{name}`", lab, row, verdict(row)))
    L("")
    # summary counts
    vs = [verdict(r) for _, _, _, a, b in arms for r in (a, b) if r]
    early = sum(v.startswith("early") for v in vs)
    same = sum(v.startswith("same") for v in vs)
    late = sum(v.startswith("late") for v in vs)
    short = sum(v == "too short" for v in vs)
    restarts = sum(v.startswith("restart") for v in vs)
    L("## Reading")
    L("")
    L(f"Throats read at t = {T_VERDICT:.0f}: {early} early, {same} same, {late} late, "
      f"{short} too short, {restarts} restart arms (own clock only).")
    L("")
    L("- *early* = the companion has moved that throat's origin clock forward relative")
    L("  to an isolated throat: the environment is selecting (accelerating) the")
    L("  contraction branch there.")
    L("- *same* = neutral: the throat is on the isolated schedule until the plunge and")
    L("  V1's natural run cannot expect the environment to do the collapsing for it.")
    L("- *late / never* = the companion is holding the throat open longer than it would")
    L("  hold itself, which on the like-signed (repelling) arms is the expected sign of")
    L("  the inflation branch and should be checked against their areal radius.")
    L("")
    L("**Caveats.** The monitor is the compactified origin, not the throat, and it is")
    L("gauge-dependent (the orbital arms carry a shift the isolated throat does not).")
    L("The isolated throat's areal radius turns over at t = 26 while its origin chi")
    L(f"peaks at t = {ref['t_max']:.1f}, so the origin is a *late* proxy. Restart arms begin at")
    L("t = 30-50 from a state already deep in the mode and are normalised to that")
    L("state, so only their floor column means anything. On merging arms the")
    L("half-space split loses meaning once the throats cross the midplane (sep < ~2),")
    L("so columns past contact (t >~ 30 head-on, >~ 45 orbital) read the merged core.")
    L("")
    (root / "single_throat" / "CLOCK_COMPARISON.md").write_text("\n".join(lines) + "\n")

    # figure
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        fig, ax = plt.subplots(figsize=(9, 5.5))
        for name, t, c, rowA, rowB in arms:
            ratio = c[:, COL["chiA"]] / c[0, COL["chiA"]]
            ax.plot(t, ratio, lw=0.8, alpha=0.6, label=None)
            if rowB is not None:
                ratioB = c[:, COL["chiB"]] / c[0, COL["chiB"]]
                ax.plot(t, ratioB, lw=0.8, alpha=0.6, ls="--")
        ax.plot(t_ref, c_ref[:, COL["chiA"]] / c_ref[0, COL["chiA"]], "k", lw=2.5,
                label=f"{REFERENCE} (isolated)")
        ax.axvline(T_TURNOVER, color="k", ls=":", lw=1)
        ax.set_yscale("log")
        ax.set_xlabel("t (code units)")
        ax.set_ylabel("chi at the origin / its t = 0 value")
        ax.set_title("origin-chi clock, every arm (thin: binaries, A solid / B dashed)")
        ax.legend(loc="upper left")
        ax.grid(alpha=0.3)
        fig.tight_layout()
        (root / "figures").mkdir(exist_ok=True)
        fig.savefig(root / "figures" / "throat_clock_comparison.png", dpi=130)
    except Exception as e:  # noqa: BLE001
        print("figure skipped:", e)
    print("wrote", root / "single_throat" / "CLOCK_COMPARISON.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
