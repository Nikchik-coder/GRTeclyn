#!/usr/bin/env python3
"""Check manuscript numbers against archived JSON and generate TeX macros."""

import argparse
import csv
import hashlib
import json
from pathlib import Path


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]


def checked_rows():
    with (HERE / "ledger_results.tsv").open() as stream:
        rows = list(csv.DictReader(stream, delimiter="\t"))
    names = set()
    for row in rows:
        name = row["macro"]
        if not name.isalpha() or not name.startswith("clm") or name in names:
            raise ValueError(f"Invalid or duplicate macro: {name}")
        names.add(name)
        path = ROOT / row["source"]
        if hashlib.sha256(path.read_bytes()).hexdigest() != row["sha256"]:
            raise ValueError(f"Source changed: {row['source']}")
        value = json.loads(path.read_text())
        for key in row["pointer"].strip("/").split("/"):
            value = value[int(key)] if isinstance(value, list) else value[key]
        if value != json.loads(row["value"]):
            raise ValueError(f"Value mismatch: {name}")
        if not row["tex"]:
            raise ValueError(f"Missing manuscript value: {name}")
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("check", "tex"))
    args = parser.parse_args()
    rows = checked_rows()
    if args.command == "tex":
        content = "% Generated by claims/claims.py tex; edit the ledger instead.\n"
        content += "".join(
            "\\newcommand{\\%s}{\\ensuremath{%s}}\n" % (row["macro"], row["tex"])
            for row in rows
        )
        (HERE.parent / "numbers.tex").write_text(content)
    print(f"{len(rows)} manuscript numbers match their archived sources.")


if __name__ == "__main__":
    main()
