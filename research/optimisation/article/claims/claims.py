#!/usr/bin/env python3
"""Check the selection ledger against raw data; generate article number macros."""
import argparse
import csv
import gzip
import hashlib
import json
from pathlib import Path
import numpy as np
import physics
import analytic
from grteclyn_wrapper.visualisation.optimisation.paper_results import REPO, load_models
from grteclyn_wrapper.visualisation.optimisation.plot_convergence import load, order_rows, PACKED
from grteclyn_wrapper.visualisation.optimisation.plot_instability_curve import load as load_growth, GROWTH_TABLE
from grteclyn_wrapper.visualisation.optimisation.plot_contraction_delay import load as load_delay, TABLE as DELAY_TABLE
OUT = Path(__file__).resolve().parents[1] / "numbers.tex"

def check(rows):
    physics_rows = physics.load_checked(REPO)
    analytic.selected(REPO)
    for row in rows:
        source = REPO / row['source']
        if row['stage'] == 'search':
            with source.open() as f:
                candidates = list(csv.DictReader(f, delimiter='\t'))
            raw = candidates[row['record'] - 1]
            good = [r for r in candidates if r['verdict'] == 'PASS' and np.isfinite(float(r['X']))]
            assert float(raw['X']) == min(float(r['X']) for r in good), row['id']
            assert raw['verdict'] == 'PASS'
            pairs = [(k, raw[k]) for k in ('mass','q1','q2','q3','X','E19','E_c')]
        else:
            raw = json.loads(str(np.load(source)['meta']))
            pairs = [('mass',raw['m'])] + [(f'q{i+1}',v) for i,v in enumerate(raw['q'])]
            pairs += [(k,raw[k]) for k in ('X','E19','E_c')]
            assert raw['verdict'] == 'PASS'
        for key, value in pairs:
            assert np.isclose(row[key],float(value),rtol=1e-12,atol=0), (row['id'],key)
        assert max(row['E19'],row['E_c']) <= 1e-8
    for entry in json.loads((PACKED/'stream_manifest.json').read_text()):
        raw = gzip.decompress((PACKED/entry['path']).read_bytes())
        assert hashlib.sha256(raw).hexdigest() == entry['sha256_raw']
    for folder in ('completed/2026-10-31/d46/evolution',
                   'validation/2026-10-31-extensions/boson-k0-cma-r2',
                   'validation/2026-10-31-extensions/s0-continuation-strict'):
        root = REPO / 'results/optimisation' / folder
        for entry in json.loads((root/'archive_manifest.json').read_text()):
            assert hashlib.sha256((root/entry['archive']).read_bytes()).hexdigest() == entry['archive_sha256']
    movie_root = REPO / 'results/optimisation/completed/2026-10-31/d46/evolution'
    for movie in json.loads((movie_root/'movie_closeout.json').read_text())['movies']:
        assert hashlib.sha256((movie_root/'movies'/movie['file']).read_bytes()).hexdigest() == movie['sha256']
    data = load()
    expected = order_rows(data)
    with (PACKED/'constraint_orders.tsv').open() as f:
        actual = list(csv.DictReader(f,delimiter='\t'))
    assert len(actual) == len(expected)
    for a,b in zip(actual,expected):
        for k in ('p96_128','p128_192'):
            assert np.isclose(float(a[k]),b[k],rtol=1e-12)
    points, candidates, _ = load_growth()
    analytic.check_ledger(REPO, analytic.values(REPO, data, physics_rows, points, candidates))
    with GROWTH_TABLE.open() as f:
        growth = list(csv.DictReader(f, delimiter='\t'))
    assert len(growth) == len(points) + len(candidates)
    for saved, measured in zip(growth, points + candidates):
        for key, value in measured.items():
            if isinstance(value, str):
                assert saved[key] == value, key
            else:
                assert np.isclose(float(saved[key]), value, rtol=1e-12, atol=0), key
    _, delay_rows = load_delay()
    with DELAY_TABLE.open() as f:
        saved_delay = list(csv.DictReader(f, delimiter='\t'))
    assert len(saved_delay) == len(delay_rows)
    for saved, measured in zip(saved_delay, delay_rows):
        for key, value in measured.items():
            if isinstance(value, str):
                assert saved[key] == value
            elif value is None:
                assert saved[key] == ''
            else:
                assert np.isclose(float(saved[key]), value, rtol=1e-12, atol=0)
    print(f'Checked {len(delay_rows)} contraction-threshold times.')
    print(f'Checked {len(rows)} selected candidates, {len(expected)} order pairs and {len(growth)} growth fits.')
    return data

def generate(rows, data):
    chunks = ['% Generated by claims/claims.py tex; edit the selection ledger, not this file.']
    def macro(name, body): chunks.append('\\newcommand{\\'+name+'}{%\n'+body+'%\n}')
    physics_rows = physics.load_checked(REPO)
    physics.generate(physics_rows, macro)
    points, candidates, _ = load_growth()
    analytic.generate(analytic.check_ledger(REPO, analytic.values(REPO, data, physics_rows, points, candidates)), macro)
    analytic.selected_tex(analytic.selected(REPO), macro)
    for kind in ('models','exoticity'):
        body=[]
        for family in ('Drainhole','Symmetric'):
            cols = 5 if kind == 'models' else 4
            body.append(r'\multicolumn{'+str(cols)+r'}{l}{'+family+r', $150\times30$ search grid} \\')
            for row in rows:
                if row['family'] != family or row['stage'] != 'search': continue
                values = ([row[k] for k in ('mass','q1','q2','q3')] if kind == 'models'
                          else [row['X'],row['X_v0']])
                line = row['model']+' & '+' & '.join(f'${v:.3f}$' for v in values)
                if kind == 'exoticity': line += f" & ${row['delta']:+.1f}\\%$"
                body.append(line+r' \\')
            body.append(r'\hline')
        cols = 5 if kind == 'models' else 4
        body.append(r'\multicolumn{'+str(cols)+r'}{l}{Selected $210\times42$ solution} \\')
        r=next(r for r in rows if r['stage']=='fine')
        values=([r[k] for k in ('mass','q1','q2','q3')] if kind=='models' else [r['X'],r['X_v0']])
        line=r'D21$^\star$ & '+' & '.join(f'${v:.3f}$' for v in values)
        if kind=='exoticity': line+=f" & ${r['delta']:+.1f}\\%$"
        body.append(line+r' \\')
        macro('clm'+kind.title()+'Rows','\n'.join(body)+'\n')
    orders=order_rows(data);body=[]
    for level in range(4):
        for constraint in ('Ham','Mom'):
            selected=[r for r in orders if r['level']==level and r['constraint']==constraint]
            body.append(f'{constraint} L{level} & '+' & '.join(f"{r['p96_128']:.2f} / {r['p128_192']:.2f}" for r in selected)+r' \\')
    macro('clmOrderRows','\n'.join(body)+'\n')
    fine=next(r for r in rows if r['stage']=='fine')
    search=next(r for r in rows if r['id']=='D21' and r['stage']=='search')
    macro('clmDsearchX',f"{search['X']:.3f}")
    macro('clmDfineX',f"{fine['X']:.3f}")
    macro('clmDfineReduction',f"{abs(fine['delta']):.1f}")
    macro('clmDfineReductionRounded',f"{abs(fine['delta']):.0f}")
    for key in ('E19','E_c'):
        v=fine[key]; exponent=int(np.floor(np.log10(v)))
        macro('clmDfine'+('EoneNine' if key=='E19' else 'Ec'),f'{v/10**exponent:.1f}\\times10^{{{exponent}}}')
    for n,d in data.items():
        g=d['geometry']; first=np.flatnonzero(g[:,1]/g[0,1]<=.99)[0]
        name={96:'Low',128:'Mid',192:'High'}[n]
        macro('clmContraction'+name,f'{g[first,0]:.1f}')
    points, candidates, _ = load_growth()
    candidate = next(p for p in candidates if p['label'] == 'D21 potential')
    reference = next(p for p in points if p['label'] == 'D21')
    macro('clmGrowthClassicalTau',f"{reference['tau']:.2f}")
    macro('clmGrowthPotentialTau',f"{candidate['tau']:.2f}")
    macro('clmGrowthReduction',f"{100*(1-candidate['rate']/reference['rate']):.0f}")
    d0 = next(p for p in candidates if p['label'] == 'D0 potential')
    ref0 = next(p for p in points if p['label'] == 'D0')
    macro('clmGrowthDzeroReduction', f"{100*(1-d0['rate']/ref0['rate']):.0f}")
    d30 = next(p for p in candidates if p['label'] == 'D30 potential')
    ref30 = next(p for p in points if p['label'] == 'D30')
    macro('clmGrowthDthirtyReduction', f"{100*(1-d30['rate']/ref30['rate']):.0f}")
    d40 = next(p for p in candidates if p['label'] == 'D40 potential')
    ref40 = next(p for p in points if p['label'] == 'D40')
    macro('clmGrowthDfortyIncrease', f"{100*(d40['rate']/ref40['rate']-1):.0f}")
    _, delay_rows = load_delay()
    d46_times = {r['branch']: r['time'] for r in delay_rows
                 if r['model'] == 'D46' and r['deficit'] == .01}
    macro('clmDelayDfortysix', f"{d46_times['potential']-d46_times['classical']:.1f}")
    OUT.write_text('\n'.join(chunks)+'\n')
    print(OUT)

def main():
    ap=argparse.ArgumentParser();ap.add_argument('command',choices=('check','tex'));args=ap.parse_args()
    rows=load_models();data=check(rows)
    if args.command=='tex':generate(rows,data)
if __name__=='__main__':main()
